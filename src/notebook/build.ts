import { qualifiedName } from '../catalog/ddl';
import { isAzureLake } from '../connections/profile';
import type { ConnectionProfile } from '../connections/profile';
import { AantjeError } from '../errors';
import { firstSchemaQuery } from '../data/attach';
import { MEMORY_LIMIT } from '../data/instance';
import { PREVIEW_LIMIT } from '../data/types';
import type { S3Settings, TableRef } from '../data/types';
import { inlineCode } from '../tree/format';
import { pyString } from './python';

export interface NotebookCell {
  readonly kind: 'markdown' | 'code';
  readonly language: 'markdown' | 'python';
  readonly source: string;
}

export interface NotebookSpec {
  readonly connectionName: string;
  /** Never carries a password. */
  readonly profile: ConnectionProfile;
  readonly table: TableRef;
  /** Undefined: the notebook follows the latest snapshot. */
  readonly snapshot?: SnapshotId;
  /** The snapshot the tree showed; informational. */
  readonly shownSnapshot?: SnapshotId;
  /** Settings values, never credentials. */
  readonly s3: S3Settings;
  readonly extensionDirectory?: string;
  /** `YYYY-MM-DD`; passed in so that the function stays pure. */
  readonly generatedOn: string;
}

const KIND_NAMES = {
  postgres: 'PostgreSQL',
  sqlite: 'SQLite',
  duckdb: 'DuckDB',
  quack: 'DuckDB + Quack',
} as const;

// The extensions next to ducklake; Quack sends its requests through httpfs.
const CATALOG_EXTENSIONS: Readonly<Record<ConnectionProfile['kind'], readonly string[]>> = {
  postgres: ['postgres'],
  sqlite: ['sqlite'],
  duckdb: [],
  quack: ['quack', 'httpfs'],
};

// The variable that holds the password or token; the configuration cell reads it, the connection cell deletes it.
const SECRET_VARIABLES: Readonly<Record<ConnectionProfile['kind'], string | undefined>> = {
  postgres: 'PG_PASSWORD',
  sqlite: undefined,
  duckdb: undefined,
  quack: 'QUACK_TOKEN',
};

/**
 * The cells attach the catalog and read its data files with plain DuckDB. An Azure DuckLake also needs the azure
 * extension, a token for the storage account and, with Entra, a token instead of a password; the cells do none of it,
 * so the notebook of such a lake would fail at the attach or at the first query. Refused before anything is read.
 */
export function assertNotebookSupported(profile: ConnectionProfile): void {
  if (isAzureLake(profile)) {
    throw new AantjeError(
      'INVALID_PROFILE',
      `Create Notebook does not support the Azure DuckLake "${profile.name}" yet: the notebook cannot sign in to its PostgreSQL server or read its storage account. Use the SQL editor, or the Azure notebooks of the Docker stack (Copy Azure Config).`,
    );
  }
}

/** Builds the cells of a notebook that queries one table; its attach SQL mirrors `src/data/attach.ts`. */
export function buildNotebook(spec: NotebookSpec): NotebookCell[] {
  assertNotebookSupported(spec.profile);
  const tableName = `${spec.table.schema}.${spec.table.table}`;
  return [
    markdown(titleCell(spec, tableName)),
    code(['%pip install "duckdb>=2.0.0" pandas']),
    code(importsCell()),
    code(configurationCell(spec)),
    code(connectCell(spec.profile)),
    markdown(askCell()),
    code(queryCell(spec.table)),
    markdown(nextStepsCell(spec.profile)),
  ];
}

function markdown(lines: readonly string[]): NotebookCell {
  return { kind: 'markdown', language: 'markdown', source: lines.join('\n') };
}

function code(lines: readonly string[]): NotebookCell {
  return { kind: 'code', language: 'python', source: lines.join('\n') };
}

function titleCell(spec: NotebookSpec, tableName: string): string[] {
  const kind = KIND_NAMES[spec.profile.kind];
  const shown =
    spec.shownSnapshot === undefined ? '' : ` (the explorer showed snapshot ${spec.shownSnapshot})`;
  const snapshot =
    spec.snapshot === undefined
      ? `follows the latest snapshot${shown}`
      : `pinned to snapshot ${spec.snapshot}`;
  const secretSource =
    spec.profile.kind === 'postgres'
      ? 'The PostgreSQL password is read from the environment variable `PGPASSWORD` or asked for when you run the configuration cell. '
      : spec.profile.kind === 'quack'
        ? 'The token of the Quack server is read from the environment variable `QUACK_TOKEN` or asked for when you run the configuration cell. '
        : '';
  const attached = spec.profile.kind === 'quack' ? '' : ' read-only';
  return [
    `# ${inlineCode(tableName)}`,
    '',
    `Generated by aantje on ${spec.generatedOn} for ${inlineCode(tableName)} of the connection ${inlineCode(spec.connectionName)} (${kind} catalog). The notebook attaches the DuckLake catalog${attached} with DuckDB and queries it.`,
    '',
    `- **Snapshot:** ${snapshot}. Change \`SNAPSHOT\` in the configuration cell to read another snapshot.`,
    '- **Kernel:** select a Python 3 kernel in the Jupyter extension. The first code cell installs `duckdb` and `pandas`; if the import fails afterwards, restart the kernel and run the cells again from the second code cell.',
    '- **Run:** run the cells from top to bottom, then edit `QUERY` to ask your own question.',
    `- **Secrets:** this notebook stores no password. ${secretSource}S3 credentials come from \`AWS_ACCESS_KEY_ID\` and \`AWS_SECRET_ACCESS_KEY\`; a missing one is asked for when an S3 endpoint is configured. The connection cell deletes the secrets from the kernel after use, so run the cells from the configuration cell on.`,
  ];
}

function importsCell(): string[] {
  return [
    'import atexit',
    'import getpass',
    'import os',
    'import shutil',
    'import tempfile',
    '',
    'import duckdb',
    '',
    '',
    'def lit(value):',
    '    """Quote a value as a SQL string literal."""',
    `    return "'" + str(value).replace("'", "''") + "'"`,
  ];
}

function configurationCell({ profile, snapshot, s3, extensionDirectory }: NotebookSpec): string[] {
  return [
    ...catalogVariables(profile),
    '',
    '# Snapshot to read; None follows the latest snapshot.',
    `SNAPSHOT = ${snapshot ?? 'None'}`,
    '',
    '# S3: only needed when the data files of the table are stored on S3.',
    '# AWS without an endpoint: set the environment variables, or assign S3_KEY_ID and S3_SECRET_KEY with getpass.getpass().',
    `S3_ENDPOINT = ${optionalString(s3.endpoint)}`,
    `S3_REGION = ${optionalString(s3.region)}`,
    `S3_URL_STYLE = ${optionalString(s3.urlStyle)}`,
    "S3_KEY_ID = os.environ.get('AWS_ACCESS_KEY_ID')",
    "S3_SECRET_KEY = os.environ.get('AWS_SECRET_ACCESS_KEY')",
    'if S3_ENDPOINT and not S3_KEY_ID:',
    "    S3_KEY_ID = getpass.getpass('S3 access key id: ')",
    'if S3_ENDPOINT and not S3_SECRET_KEY:',
    "    S3_SECRET_KEY = getpass.getpass('S3 secret access key: ')",
    '',
    '# Where DuckDB keeps its extensions; None uses the DuckDB default and downloads them on first use.',
    `EXTENSION_DIRECTORY = ${optionalString(extensionDirectory)}`,
  ];
}

function catalogVariables(profile: ConnectionProfile): string[] {
  if (profile.kind === 'quack') {
    return [
      '# DuckLake catalog (DuckDB + Quack server).',
      `QUACK_HOST = ${pyString(profile.host)}`,
      `QUACK_PORT = ${profile.port}`,
      "QUACK_TOKEN = os.environ.get('QUACK_TOKEN') or getpass.getpass('Quack token: ')",
      `QUACK_TLS = ${profile.ssl ? 'True' : 'False'}`,
      '# SHA-256 fingerprint of the server certificate; None checks it against the system trust store.',
      `QUACK_FINGERPRINT = ${optionalString(profile.ssl ? profile.fingerprint : undefined)}`,
    ];
  }
  if (profile.kind !== 'postgres') {
    return [
      `# DuckLake catalog (${KIND_NAMES[profile.kind]} file).`,
      `CATALOG_PATH = ${pyString(profile.path)}`,
    ];
  }
  return [
    '# DuckLake catalog (PostgreSQL).',
    `PG_HOST = ${pyString(profile.host)}`,
    `PG_PORT = ${profile.port}`,
    `PG_DATABASE = ${pyString(profile.database)}`,
    `PG_USER = ${pyString(profile.user)}`,
    "PG_PASSWORD = os.environ.get('PGPASSWORD') or getpass.getpass('PostgreSQL password: ')",
    `PG_SSL = ${profile.ssl === true ? 'True' : 'False'}`,
    `PG_METADATA_SCHEMA = ${optionalString(profile.metadataSchema)}`,
  ];
}

function optionalString(value: string | undefined): string {
  const trimmed = value?.trim() ?? '';
  return trimmed === '' ? 'None' : pyString(trimmed);
}

function connectCell(profile: ConnectionProfile): string[] {
  const extensions = ['ducklake', ...CATALOG_EXTENSIONS[profile.kind]]
    .map((name) => pyString(name))
    .join(', ');
  const secret = SECRET_VARIABLES[profile.kind];
  return [
    '# Like the extension: no secrets written to disk, a private temporary directory, a memory limit.',
    "TEMP_DIRECTORY = tempfile.mkdtemp(prefix='aantje-duckdb-')",
    'atexit.register(shutil.rmtree, TEMP_DIRECTORY, ignore_errors=True)',
    `config = {'allow_persistent_secrets': 'false', 'temp_directory': TEMP_DIRECTORY, 'memory_limit': '${MEMORY_LIMIT}'}`,
    'if EXTENSION_DIRECTORY:',
    "    config['extension_directory'] = EXTENSION_DIRECTORY",
    'con = duckdb.connect(config=config)',
    '',
    'use_s3 = bool(S3_ENDPOINT or (S3_KEY_ID and S3_SECRET_KEY))',
    `extensions = [${extensions}]`,
    "if use_s3 and 'httpfs' not in extensions:",
    "    extensions.append('httpfs')",
    'for extension in extensions:',
    "    con.execute('INSTALL ' + extension)",
    "    con.execute('LOAD ' + extension)",
    '',
    ...s3SecretLines(),
    ...(profile.kind === 'postgres' ? postgresSecretLines() : []),
    ...(profile.kind === 'quack' ? quackSecretLines() : []),
    '',
    ...attachLines(profile),
    '# After the ATTACH nothing installs or loads an extension on its own any more.',
    "con.execute('SET autoinstall_known_extensions = false')",
    "con.execute('SET autoload_known_extensions = false')",
    ...useLakeLines(),
    '',
    '# The kernel keeps no secrets after the connection is made.',
    `del ${secret ? `${secret}, ` : ''}S3_KEY_ID, S3_SECRET_KEY`,
  ];
}

// `USE lake` fails for a lake without the schema `main`; its first schema becomes the default then, as in the SQL editor.
function useLakeLines(): string[] {
  return [
    'try:',
    "    con.execute('USE lake')",
    'except duckdb.Error:',
    `    first = con.execute(${pyString(firstSchemaQuery())}).fetchone()`,
    '    if first is None:',
    '        raise',
    `    con.execute('USE lake."' + first[0].replace('"', '""') + '"')`,
  ];
}

function quackSecretLines(): string[] {
  return [
    "QUACK_URI = 'quack:' + QUACK_HOST + ':' + str(QUACK_PORT)",
    "con.execute('CREATE OR REPLACE TEMPORARY SECRET aantje_quack (TYPE quack, TOKEN ' + lit(QUACK_TOKEN) + ', SCOPE ' + lit(QUACK_URI) + ')')",
    '',
  ];
}

function s3SecretLines(): string[] {
  return [
    'if use_s3:',
    '    s3 = []',
    '    if S3_KEY_ID and S3_SECRET_KEY:',
    "        s3.append('KEY_ID ' + lit(S3_KEY_ID))",
    "        s3.append('SECRET ' + lit(S3_SECRET_KEY))",
    '    if S3_REGION:',
    "        s3.append('REGION ' + lit(S3_REGION))",
    '    if S3_ENDPOINT:',
    '        endpoint = S3_ENDPOINT',
    '        use_ssl = None',
    "        if endpoint.lower().startswith(('http://', 'https://')):",
    "            use_ssl = endpoint.lower().startswith('https')",
    "            endpoint = endpoint.split('://', 1)[1]",
    "        s3.append('ENDPOINT ' + lit(endpoint.rstrip('/')))",
    '        if use_ssl is not None:',
    "            s3.append('USE_SSL ' + ('true' if use_ssl else 'false'))",
    '        del endpoint, use_ssl',
    '    if S3_URL_STYLE:',
    "        s3.append('URL_STYLE ' + lit(S3_URL_STYLE))",
    "    con.execute('CREATE OR REPLACE SECRET aantje_s3 (TYPE s3, ' + ', '.join(s3) + ')')",
    '    del s3',
  ];
}

function postgresSecretLines(): string[] {
  return [
    "pg = ['HOST ' + lit(PG_HOST), 'PORT ' + str(PG_PORT), 'DATABASE ' + lit(PG_DATABASE), 'USER ' + lit(PG_USER)]",
    'if PG_PASSWORD:',
    "    pg.append('PASSWORD ' + lit(PG_PASSWORD))",
    'if PG_SSL:',
    '    pg.append("SSLMODE \'verify-full\'")',
    '    pg.append("SSLROOTCERT \'system\'")',
    'else:',
    '    pg.append("SSLMODE \'disable\'")',
    "con.execute('CREATE OR REPLACE SECRET aantje_pg (TYPE postgres, ' + ', '.join(pg) + ')')",
    'del pg',
    '',
  ];
}

function attachLines(profile: ConnectionProfile): string[] {
  const options =
    profile.kind === 'postgres'
      ? [
          "options = ['READ_ONLY', \"META_SECRET 'aantje_pg'\"]",
          'if PG_METADATA_SCHEMA:',
          "    options.append('METADATA_SCHEMA ' + lit(PG_METADATA_SCHEMA))",
        ]
      : profile.kind === 'quack'
        ? [
            "options = ['CREATE_IF_NOT_EXISTS false', 'META_DISABLE_SSL ' + ('false' if QUACK_TLS else 'true')]",
            'if QUACK_TLS and QUACK_FINGERPRINT:',
            "    options.append('META_SSL_FINGERPRINT ' + lit(QUACK_FINGERPRINT))",
          ]
        : ["options = ['READ_ONLY']"];
  const target =
    profile.kind === 'postgres'
      ? "'ducklake:postgres:'"
      : profile.kind === 'quack'
        ? "'ducklake:' + QUACK_URI"
        : profile.kind === 'sqlite'
          ? "'ducklake:sqlite:' + CATALOG_PATH"
          : "'ducklake:' + CATALOG_PATH";
  return [
    ...options,
    'if SNAPSHOT is not None:',
    "    options.append('SNAPSHOT_VERSION ' + str(SNAPSHOT))",
    `con.execute('ATTACH ' + lit(${target}) + ' AS lake (' + ', '.join(options) + ')')`,
  ];
}

function askCell(): string[] {
  return [
    '## Ask your question',
    '',
    `Edit \`QUERY\` and run the cell again. The cell starts with the same statement as **Select Top 1000 Rows** in the explorer (\`LIMIT ${PREVIEW_LIMIT}\`); DuckDB has no \`TOP\`. The catalog is attached as \`lake\`, so tables are addressed as \`lake."schema"."table"\`; the name of a schema can be the same as the name of a catalog, and the prefix keeps the statement unambiguous.`,
  ];
}

function queryCell(table: TableRef): string[] {
  const query = `SELECT * FROM lake.${qualifiedName(table.schema, table.table)} LIMIT ${PREVIEW_LIMIT}`;
  return [`QUERY = ${pyString(query, true)}`, 'con.sql(QUERY).df()'];
}

function nextStepsCell(profile: ConnectionProfile): string[] {
  // DuckDB 2.0.0 accepts READ_ONLY for Quack without enforcing it, and newer quack builds refuse it, so a Quack lake is
  // attached without it.
  const readOnly =
    profile.kind === 'quack'
      ? 'A Quack catalog is not attached read-only: what the token may change is decided by the server.'
      : 'The catalog is attached read-only, so the notebook cannot change it.';
  return [
    '## Next steps',
    '',
    `- Change \`QUERY\` and run the cell again. ${readOnly}`,
    '- Print the result as text with `con.sql(QUERY).show()` or fetch it as Python tuples with `con.sql(QUERY).fetchall()`.',
    '- Time travel: set `SNAPSHOT` in the configuration cell and run the cells from there on. List the snapshots with `con.sql("SELECT * FROM ducklake_snapshots(\'lake\')").df()`.',
  ];
}
