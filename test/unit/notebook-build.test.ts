describe('buildNotebook for the other catalog kinds', () => {
  it('writes a PostgreSQL profile with the password from the environment or a prompt, TLS and the metadata schema as configured', () => {
    const cells = buildNotebook(
      spec({
        connectionName: 'prod',
        profile: { ...postgresProfile, ssl: true, metadataSchema: 'lake_meta' },
      }),
    );
    expect(sourceOf(cells[CONFIGURATION]).split('\n').slice(0, 9)).toEqual([
      '# DuckLake catalog (PostgreSQL).',
      "PG_HOST = 'db.example.com'",
      'PG_PORT = 5433',
      "PG_DATABASE = 'lake'",
      "PG_USER = 'reader'",
      "PG_PASSWORD = os.environ.get('PGPASSWORD') or getpass.getpass('PostgreSQL password: ')",
      'PG_SSL = True',
      "PG_METADATA_SCHEMA = 'lake_meta'",
      '',
    ]);
    const connect = sourceOf(cells[CONNECT]);
    expect(connect).toContain("extensions = ['ducklake', 'postgres']");
    expect(connect).toContain(
      lines(
        "pg = ['HOST ' + lit(PG_HOST), 'PORT ' + str(PG_PORT), 'DATABASE ' + lit(PG_DATABASE), 'USER ' + lit(PG_USER)]",
        'if PG_PASSWORD:',
        "    pg.append('PASSWORD ' + lit(PG_PASSWORD))",
        'if PG_SSL:',
        '    pg.append("SSLMODE \'verify-full\'")',
        '    pg.append("SSLROOTCERT \'system\'")',
        'else:',
        '    pg.append("SSLMODE \'disable\'")',
        "con.execute('CREATE OR REPLACE SECRET aantje_pg (TYPE postgres, ' + ', '.join(pg) + ')')",
        'del pg',
      ),
    );
    expect(connect).toContain(
      lines(
        "options = ['READ_ONLY', \"META_SECRET 'aantje_pg'\"]",
        'if PG_METADATA_SCHEMA:',
        "    options.append('METADATA_SCHEMA ' + lit(PG_METADATA_SCHEMA))",
        'if SNAPSHOT is not None:',
        "    options.append('SNAPSHOT_VERSION ' + str(SNAPSHOT))",
        "con.execute('ATTACH ' + lit('ducklake:postgres:') + ' AS lake (' + ', '.join(options) + ')')",
      ),
    );
    expect(connect).toContain('\ndel PG_PASSWORD, S3_KEY_ID, S3_SECRET_KEY');
    expect(sourceOf(cells[INTRO])).toContain(
      'The PostgreSQL password is read from the environment variable `PGPASSWORD` or asked for when you run the configuration cell.',
    );

    const plain = buildNotebook(spec({ connectionName: 'prod', profile: postgresProfile }));
    expect(sourceOf(plain[CONFIGURATION])).toContain(lines('PG_SSL = False', 'PG_METADATA_SCHEMA = None'));
  });

  it('attaches a DuckDB file catalog with the plain ducklake: prefix and needs no second extension; a file catalog never mentions PostgreSQL', () => {
    const cells = buildNotebook(spec({ connectionName: 'local', profile: duckdbProfile }));
    expect(sourceOf(cells[INTRO])).toContain('(DuckDB catalog)');
    expect(sourceOf(cells[CONFIGURATION])).toContain(
      lines('# DuckLake catalog (DuckDB file).', "CATALOG_PATH = '/data/lake.duckdb'"),
    );
    const connect = sourceOf(cells[CONNECT]);
    expect(connect).toContain("extensions = ['ducklake']");
    expect(connect).toContain("lit('ducklake:' + CATALOG_PATH)");

    for (const profile of [sqliteProfile, duckdbProfile]) {
      const text = buildNotebook(spec({ profile })).map(sourceOf).join('\n');
      expect(text, profile.kind).not.toMatch(/PGPASSWORD|PG_|postgres/i);
    }
  });
});

describe('buildNotebook snapshot handling', () => {
  it('pins the snapshot of the spec, 0 included, and otherwise follows the latest one and says which one the tree showed', () => {
    const cases: [snapshot: number | undefined, shown: number | undefined, config: string, intro: string][] =
      [
        [5, 5, 'SNAPSHOT = 5', '- **Snapshot:** pinned to snapshot 5.'],
        [0, 0, 'SNAPSHOT = 0', '- **Snapshot:** pinned to snapshot 0.'],
        [5, 9, 'SNAPSHOT = 5', '- **Snapshot:** pinned to snapshot 5.'],
        [
          undefined,
          13,
          'SNAPSHOT = None',
          '- **Snapshot:** follows the latest snapshot (the explorer showed snapshot 13).',
        ],
        [undefined, undefined, 'SNAPSHOT = None', '- **Snapshot:** follows the latest snapshot.'],
      ];
    for (const [snapshot, shownSnapshot, config, intro] of cases) {
      const cells = buildNotebook(spec({ snapshot, shownSnapshot }));
      const name = `${snapshot} shown ${shownSnapshot}`;
      expect(sourceOf(cells[CONFIGURATION]), name).toContain(
        lines('# Snapshot to read; None follows the latest snapshot.', config),
      );
      expect(sourceOf(cells[INTRO]), name).toContain(intro);
    }
    expect(sourceOf(buildNotebook(spec({ snapshot: 5, shownSnapshot: 9 }))[INTRO])).not.toContain(
      'explorer showed',
    );
  });
});

describe('buildNotebook S3 and extension settings', () => {
  it('fills the variables from the settings, trimmed, and turns empty and blank settings into None', () => {
    const filled = sourceOf(
      buildNotebook(
        spec({
          s3: { endpoint: ' http://localhost:9000 ', region: 'eu-central-1', urlStyle: 'path' },
          extensionDirectory: String.raw`D:\duckdb\extensions`,
        }),
      )[CONFIGURATION],
    );
    expect(filled).toContain(
      lines("S3_ENDPOINT = 'http://localhost:9000'", "S3_REGION = 'eu-central-1'", "S3_URL_STYLE = 'path'"),
    );
    expect(filled).toContain(String.raw`EXTENSION_DIRECTORY = 'D:\\duckdb\\extensions'`);

    const empty = sourceOf(
      buildNotebook(
        spec({ s3: { endpoint: '', region: '  ', urlStyle: undefined }, extensionDirectory: '' }),
      )[CONFIGURATION],
    );
    expect(empty).toContain(lines('S3_ENDPOINT = None', 'S3_REGION = None', 'S3_URL_STYLE = None'));
    expect(empty).toContain('EXTENSION_DIRECTORY = None');
  });
});

describe('buildNotebook with hostile names', () => {
  it('quotes the table in the query cell for any identifier, also one named like the catalog, and escapes the quote and the backslash in every Python literal', () => {
    expect(
      sourceOf(
        buildNotebook(spec({ table: { schema: 'we"ird', table: "it's a \\ table\nwith ünïcode" } }))[QUERY],
      ),
    ).toBe(
      lines(
        String.raw`QUERY = '''SELECT * FROM lake."we""ird"."it\'s a \\ table\nwith ünïcode" LIMIT 1000'''`,
        'con.sql(QUERY).df()',
      ),
    );
    expect(sourceOf(buildNotebook(spec({ table: { schema: 'lake', table: 'system' } }))[QUERY])).toBe(
      lines(`QUERY = '''SELECT * FROM lake."lake"."system" LIMIT 1000'''`, 'con.sql(QUERY).df()'),
    );

    const config = sourceOf(
      buildNotebook(
        spec({
          profile: { ...postgresProfile, user: "u' + PG_PASSWORD + '", metadataSchema: "m'x\\" },
          s3: { region: "r\\'" },
        }),
      )[CONFIGURATION],
    );
    expect(config).toContain(String.raw`PG_USER = 'u\' + PG_PASSWORD + \''`);
    expect(config).toContain(String.raw`PG_METADATA_SCHEMA = 'm\'x\\'`);
    expect(config).toContain(String.raw`S3_REGION = 'r\\\''`);
    expect(
      sourceOf(
        buildNotebook(
          spec({ profile: { ...sqliteProfile, path: String.raw`C:\Users\O'Neil\my lake.sqlite` } }),
        )[CONFIGURATION],
      ),
    ).toContain(String.raw`CATALOG_PATH = 'C:\\Users\\O\'Neil\\my lake.sqlite'`);
  });

  it('shows a name with backticks, line breaks or invisible format characters as one line of inline code, and cannot break out of a literal or add lines to a code cell', () => {
    const ticks = buildNotebook(spec({ connectionName: 'a`b\nc', table: { schema: 'x`', table: '`y' } }));
    const [title = '', blank = '', intro = ''] = sourceOf(ticks[INTRO]).split('\n');
    expect(title).toBe('# ``x`.`y``');
    expect(blank).toBe('');
    expect(intro).toContain('of the connection ``a`b c`` (SQLite catalog)');

    const padded = buildNotebook(spec({ connectionName: '`a', table: { schema: 'a', table: 'b`' } }));
    const [paddedTitle = '', , paddedIntro = ''] = sourceOf(padded[INTRO]).split('\n');
    expect(paddedTitle).toBe('# `` a.b` ``');
    expect(paddedIntro).toContain('for `` a.b` `` of the connection `` `a `` (SQLite catalog)');

    const separators = buildNotebook(
      spec({ connectionName: 'a\u2028b\u2029\u2029c\u202ed', table: { schema: 's', table: 't' } }),
    );
    expect(sourceOf(separators[INTRO])).toContain('of the connection `a b cd` (SQLite catalog)');

    const benign = buildNotebook(spec({ profile: postgresProfile }));
    const hostile = buildNotebook(
      spec({
        profile: {
          ...postgresProfile,
          host: "h'\nimport os; os.system('x')\r\u2028",
          database: '"\\\u0085',
          user: "u' + PG_PASSWORD + '",
        },
        table: { schema: "s'''\nimport os", table: '\u2029t' },
        s3: { endpoint: "e'\nx = 1", region: "r\\'", urlStyle: undefined },
        extensionDirectory: "d'\r\ny",
      }),
    );
    // Everything that Python source, `str.splitlines` or an editor may take for the end of a line.
    const lineBreaks = ['\r', '\u000b', '\u000c', '\u001c', '\u001d', '\u001e', '\u0085', '\u2028', '\u2029'];
    benign.forEach((cell, index) => {
      if (cell.kind === 'code') {
        expect(lineBreaks.filter((character) => sourceOf(hostile[index]).includes(character))).toEqual([]);
        expect(sourceOf(hostile[index]).split('\n')).toHaveLength(cell.source.split('\n').length);
      }
    });
  });
});

describe('buildNotebook and secrets', () => {
  it('writes no password or key into any cell, even if the objects carry them at runtime, and reads secrets from the environment or a prompt in the configuration cell only', () => {
    const PASSWORD = 'pw-CANARY-1f6c2d';
    const KEY = 'key-CANARY-77aa';
    const SECRET = 'secret-CANARY-9be3';
    const profile = {
      ...postgresProfile,
      ssl: true,
      password: PASSWORD,
      connectionString: `postgres://u:${PASSWORD}@h/d`,
    };
    const hostile = {
      ...spec({ profile, s3: { endpoint: 'http://minio:9000', region: 'eu-west-1', urlStyle: 'path' } }),
      password: PASSWORD,
      s3Credentials: { keyId: KEY, secretKey: SECRET },
      s3: {
        endpoint: 'http://minio:9000',
        region: 'eu-west-1',
        urlStyle: 'path' as const,
        keyId: KEY,
        secretKey: SECRET,
      },
    };
    const cells = buildNotebook(hostile);
    const text = cells.map(sourceOf).join('\n');
    for (const canary of [PASSWORD, KEY, SECRET]) {
      expect(text).not.toContain(canary);
    }
    expect(cells.filter((cell) => cell.source.includes('getpass.getpass('))).toEqual([cells[CONFIGURATION]]);
  });
});

describe('buildNotebook for an Azure DuckLake', () => {
  it('refuses the lake, password or Entra, with the way out, instead of writing cells that cannot attach or read the data', () => {
    for (const azure of [
      { ...postgresProfile, azureAccount: 'lakestore' },
      { ...postgresProfile, azureAccount: 'lakestore', azureAuth: 'entra' as const },
    ]) {
      expect(() => buildNotebook(spec({ profile: azure }))).toThrow(
        expect.objectContaining({
          code: 'INVALID_PROFILE',
          userMessage: expect.stringContaining('SQL editor') as unknown,
        }) as Error,
      );
      expect(() => assertNotebookSupported(azure)).toThrow();
    }
    // A PostgreSQL catalog without a storage account is no Azure lake.
    expect(() => assertNotebookSupported(postgresProfile)).not.toThrow();
  });
});

describe('buildNotebook for a DuckDB + Quack profile', () => {
  it('attaches the served catalog with its TLS switch and pin, loads quack and httpfs, and reads the token from the environment or a prompt, never from the profile', () => {
    const TOKEN = 'tok-CANARY-41d0';
    const profile = {
      id: 'served',
      name: 'served',
      kind: 'quack' as const,
      host: 'duckdb',
      port: 9494,
      ssl: true,
      fingerprint: `${'AB:'.repeat(31)}CD`,
      token: TOKEN,
    };
    const cells = buildNotebook({
      ...spec({ connectionName: 'served', profile }),
      password: TOKEN,
    } as NotebookSpec);
    const configuration = sourceOf(cells[CONFIGURATION]);
    const connect = sourceOf(cells[CONNECT]);

    expect(cells.map(sourceOf).join('\n')).not.toContain(TOKEN);
    expect(configuration).toContain("QUACK_HOST = 'duckdb'");
    expect(configuration).toContain('QUACK_TLS = True');
    expect(configuration).toContain(`QUACK_FINGERPRINT = '${profile.fingerprint}'`);
    expect(configuration).toContain("os.environ.get('QUACK_TOKEN') or getpass.getpass(");
    expect(connect).toContain("extensions = ['ducklake', 'quack', 'httpfs']");
    expect(connect).toContain("lit('ducklake:' + QUACK_URI)");
    expect(connect).toContain("'META_SSL_FINGERPRINT ' + lit(QUACK_FINGERPRINT)");
    expect(connect).toMatch(/^del QUACK_TOKEN, /m);
    expect(connect).not.toMatch(/PG_|ca_cert_file/);
  });
});
