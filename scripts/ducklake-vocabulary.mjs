// Writes src/sql/ducklake-vocabulary.ts: the `ducklake_*` functions of the DuckLake extension of the DuckDB that aantje
// ships, read from `duckdb_functions()` of a throw-away in-memory DuckDB. `npm run vocabulary:ducklake [extension dir]`.
// The language service loads no extension, so it cannot ask DuckDB itself; `sql-ducklake-vocabulary.test.ts` fails
// when the engine and the checked-in file differ.
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(root, 'src/sql/ducklake-vocabulary.ts');
const DEFAULT_EXTENSIONS = join(root, 'test/.cache/duckdb-extensions');

// As `loadVocabulary` (src/sql/vocabulary.ts) reads the kinds of DuckDB's own functions.
const KINDS = {
  scalar: 'scalar',
  aggregate: 'aggregate',
  window: 'window',
  table: 'table',
  macro: 'macro',
  table_macro: 'table',
};

// What the binder says when the number or the types of the arguments fit no overload.
const NO_MATCH = /No function matches|does not support the supplied arguments/;

/** The `ducklake_*` functions of a connection that has DuckLake loaded, sorted by name, overloads in a stable order. */
export async function readDucklakeFunctions(connection) {
  const rows = (
    await connection.runAndReadAll(
      `SELECT function_name, function_type, parameters, parameter_types
       FROM duckdb_functions()
       WHERE starts_with(function_name, 'ducklake_')
       ORDER BY function_name, function_type, len(parameters), parameter_types::VARCHAR`,
    )
  ).getRowsJson();
  const byName = new Map();
  for (const [name, type, names, types] of rows) {
    const parameters = names.map((parameter, index) => ({ name: parameter, type: types[index] ?? 'ANY' }));
    const positional = await positionalCount(connection, name, parameters);
    const entry = byName.get(name) ?? { name, kind: KINDS[type] ?? 'scalar', overloads: [] };
    entry.overloads.push({
      parameters: parameters.slice(0, positional),
      named: parameters.slice(positional),
    });
    byName.set(name, entry);
  }
  return [...byName.values()];
}

// `duckdb_functions()` lists the named parameters of a table function after its positional ones without marking
// them. The binder tells them apart: the longest list of leading arguments that binds is the positional one (a
// shorter list may bind to a shorter overload). EXPLAIN binds without running, and the catalog argument is NULL, so no
// lake is touched (none is attached anyway). `scripts/duckdb-vocabulary.mjs` asks the same of DuckDB's own functions.
export async function positionalCount(connection, name, parameters) {
  let found;
  for (let count = 0; count <= parameters.length; count += 1) {
    // `ANY` and `ANY[]` are no type a value can be cast to.
    const values = parameters
      .slice(0, count)
      .map(({ type }) => (/\bANY\b/.test(type) ? 'NULL' : `CAST(NULL AS ${type})`));
    try {
      await connection.run(`EXPLAIN FROM ${name}(${values.join(', ')})`);
      found = count;
    } catch (error) {
      if (!NO_MATCH.test(error.message)) found = count;
    }
  }
  if (found === undefined) {
    throw new Error(`No number of arguments fits ${name}(${parameters.map((p) => p.name).join(', ')}).`);
  }
  return found;
}

/** The TypeScript module for the functions, formatted as the repository formats it. */
export async function renderDucklakeVocabulary(functions, duckdbVersion) {
  const prettier = await import('prettier');
  const source = [
    `// Generated by \`npm run vocabulary:ducklake\` (scripts/ducklake-vocabulary.mjs) from the DuckLake extension of`,
    `// DuckDB ${duckdbVersion}. Do not edit: run the script again when DuckDB or DuckLake changes.`,
    `import type { GeneratedFunction } from './ducklake';`,
    '',
    `export const DUCKLAKE_FUNCTIONS: readonly GeneratedFunction[] = ${JSON.stringify(functions)};`,
    '',
  ].join('\n');
  const options = (await prettier.resolveConfig(TARGET)) ?? {};
  return prettier.format(source, { ...options, filepath: TARGET });
}

/** Loads DuckLake from `extensionDirectory` into a new in-memory DuckDB and renders its functions. */
export async function generateDucklakeVocabulary(extensionDirectory = DEFAULT_EXTENSIONS) {
  const { DuckDBInstance } = await import('@duckdb/node-api');
  const instance = await DuckDBInstance.create(':memory:', {
    extension_directory: extensionDirectory,
    autoload_known_extensions: 'false',
  });
  const connection = await instance.connect();
  try {
    await connection.run('INSTALL ducklake');
    await connection.run('LOAD ducklake');
    const [[version]] = (await connection.runAndReadAll('SELECT version()')).getRowsJson();
    return await renderDucklakeVocabulary(await readDucklakeFunctions(connection), version);
  } finally {
    connection.closeSync();
    instance.closeSync();
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, await generateDucklakeVocabulary(process.argv[2] ?? DEFAULT_EXTENSIONS));
  console.log(`Wrote ${TARGET}.`);
}
