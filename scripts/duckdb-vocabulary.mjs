// Writes src/sql/duckdb-vocabulary.ts: where the named parameters of DuckDB's own table functions start. The language
// service reads the parameters from `duckdb_functions()`, which lists the positional and the named ones of a table
// function in one list; this file says how many are positional. Read from a throw-away in-memory DuckDB of the shipped
// `@duckdb/node-api` without extensions, like the service's. `node scripts/duckdb-vocabulary.mjs`;
// `sql-duckdb-vocabulary.test.ts` fails when the engine and the checked-in file differ.
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { positionalCount } from './ducklake-vocabulary.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(root, 'src/sql/duckdb-vocabulary.ts');

/** The number of positional parameters of the table functions that also take named ones, by name. */
export async function readPositionalCounts(connection) {
  const rows = (
    await connection.runAndReadAll(
      `SELECT function_name, parameters, parameter_types FROM duckdb_functions()
       WHERE function_type = 'table' AND regexp_matches(function_name, '^[a-zA-Z][a-zA-Z0-9_]*$')
       ORDER BY function_name, len(parameters), parameter_types::VARCHAR`,
    )
  ).getRowsJson();
  const overloads = new Map();
  for (const [name, names, types] of rows) {
    const parameters = names.map((parameter, index) => ({ name: parameter, type: types[index] ?? 'ANY' }));
    // A function that binds to no number of NULL arguments (variadic ones) keeps all its parameters positional.
    const positional = await positionalCount(connection, name, parameters).catch(() => undefined);
    overloads.set(name, [...(overloads.get(name) ?? []), { length: parameters.length, positional }]);
  }
  const counts = {};
  for (const [name, list] of overloads) {
    if (!list.some(({ length, positional }) => positional !== undefined && positional < length)) continue;
    const positional = new Set(list.map((overload) => overload.positional));
    if (positional.size > 1) {
      throw new Error(
        `The overloads of ${name} differ in their positional parameters: a count per name is not enough.`,
      );
    }
    counts[name] = list[0].positional;
  }
  return counts;
}

/** The TypeScript module for the counts, formatted as the repository formats it. */
export async function renderDuckdbVocabulary(counts, duckdbVersion) {
  const prettier = await import('prettier');
  const source = [
    `// Generated by \`node scripts/duckdb-vocabulary.mjs\` from DuckDB ${duckdbVersion}. Do not edit: run the script`,
    '// again when DuckDB changes.',
    '',
    '/** The number of positional parameters of the table functions that also take named ones, by name. */',
    `export const POSITIONAL_PARAMETERS: Readonly<Record<string, number>> = ${JSON.stringify(counts)};`,
    '',
  ].join('\n');
  const options = (await prettier.resolveConfig(TARGET)) ?? {};
  return prettier.format(source, { ...options, filepath: TARGET });
}

/** Reads the table functions of a new in-memory DuckDB that loads no extension and renders the module. */
export async function generateDuckdbVocabulary() {
  const { DuckDBInstance } = await import('@duckdb/node-api');
  const instance = await DuckDBInstance.create(':memory:', {
    enable_external_access: 'false',
    autoinstall_known_extensions: 'false',
    autoload_known_extensions: 'false',
  });
  const connection = await instance.connect();
  try {
    const [[version]] = (await connection.runAndReadAll('SELECT version()')).getRowsJson();
    return await renderDuckdbVocabulary(await readPositionalCounts(connection), version);
  } finally {
    connection.closeSync();
    instance.closeSync();
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, await generateDuckdbVocabulary());
  console.log(`Wrote ${TARGET}.`);
}
